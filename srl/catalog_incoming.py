"""Incoming skills: skills that arrive from S1 on and that no evaluation query needs. Written for this study with Claude Code (synthetic).

Kinds follow the paper's error types (Appendix C.2) so that errors can be typed by code:
  similar   - same kind of work as its target required skill but not a substitute (style 'vague' or 'specific'
              says whether its original description hides or states the difference)
  samename  - same name as its target, different body (another market, data source or scope)
  nameonly  - shares a word of its target's name, different work
  overclaim - its description claims the target's work; its body does less (planted description inconsistency)
  broad     - a shallow toolkit or overview whose description claims a whole area (scope overreach)
  generic   - general-purpose helper; no target
Each skill also has one probe: a request that this skill (and no required skill) serves, used to check that a
rewrite does not make the skill unselectable for its own work (the paper's plasticity check on incoming skills).
"""

