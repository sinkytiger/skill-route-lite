"""The 40 required skills: the skills that evaluation queries need. Written for this study with Claude Code (synthetic).

Each entry: key, install session, family, original name and description (what the router reads), body (what the
rewriters read), four test phrasings and two dev phrasings of the work. A phrasing is one sentence a user might write;
queries are built by joining phrasings of one to three skills (see build.py). "{co}" is filled with a company name.
Required skills keep their original metadata in every condition, as in the paper's main study.
"""

from __future__ import annotations


def B(name: str, purpose: str, inputs: list[str], steps: list[str], output: str, notes: list[str] = ()) -> str:
    lines = [f"# {name}", "", purpose, "", "## Inputs"] + [f"- {x}" for x in inputs]
    lines += ["", "## Steps"] + [f"{i}. {s}" for i, s in enumerate(steps, 1)] + ["", "## Output", output]
    if notes:
        lines += ["", "## Notes"] + [f"- {x}" for x in notes]
    return "\n".join(lines)


def R(key, session, family, name, desc, body, test, dev):
    assert len(test) == 4 and len(dev) == 2, key
    return {"key": key, "session": session, "family": family, "name": name, "desc": desc, "body": body,
            "phrases_test": test, "phrases_dev": dev}


